"""Called by the GitHub Action when the code guard blocks a pull request.

    python -m nightwatch.devin_ci nw.json

It hands Devin the evidence (findings, the PR, the protected functions as they were on the base
branch) and asks for two real pieces of work: a verdict on each finding, posted on the PR, and a
pull request to main with tests that pin every protection the blocked PR tried to remove, so it
can never be removed silently again. It then comments the Devin session link on the PR.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import urllib.request

from .devin import send_to_devin


def _base_source(base: str, path: str, function: str) -> str:
    src = subprocess.run(["git", "show", f"{base}:{path}"], capture_output=True, text=True).stdout
    if not src or not function:
        return ""
    import ast
    tree = ast.parse(src)
    name = function.split(".")[-1]
    for n in ast.walk(tree):
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name == name:
            return ast.get_source_segment(src, n) or ""
    return ""


def build_task(report: dict, env: dict) -> str:
    repo, pr, head, base = env.get("GITHUB_REPOSITORY", ""), env.get("PR_NUMBER", ""), env.get("HEAD_REF", ""), env.get("BASE_REF", "main")
    lines = "\n".join(f"- [{f['severity']}] {f['code']} at {f['file']}:{f['line']} in {f['function'] or 'module'}: {f['reason']}"
                      for f in report["findings"])
    seen, originals = set(), []
    for f in report["findings"]:
        key = (f["file"], f["function"])
        if f["code"] in ("GUARD_REMOVED", "OWNER_CHECK_GONE", "RAISE_REMOVED") and key not in seen:
            seen.add(key)
            src = _base_source(f"origin/{base}", f["file"], f["function"])
            if src:
                originals.append(f"{f['file']} :: {f['function']} on {base}:\n```python\n{src}\n```")
    return f"""Night Watch's code guard blocked pull request #{pr} in {repo} (branch {head} into {base}), risk {report['risk']}/100.
This is a fictional hackathon bank; no real secrets or customers are involved.

Findings (from Night Watch's AST scanner):
{lines}

The protected code as it is on {base}, before this PR:
{chr(10).join(originals) or '(no removed functions)'}

Please do two things:
1. Review PR #{pr}. For each finding decide: real weakening of a protection, or false positive, with one
   sentence of reasoning. Post that as a single comment on PR #{pr}. Do not merge, approve or push to {head}.
2. Open a NEW pull request from a new branch off {base} titled "Pin protections targeted by PR #{pr}".
   Add tests under oasis/tests/ or demo_bank/tests/ that FAIL if any protection this PR removed
   (each removed guard call, ownership check or refusal path) is removed again. Do not change product
   behaviour. Run `python3 -m pytest -q` and make sure everything passes on {base} plus your tests.
"""


def comment(body: str) -> None:
    token, repo, pr = os.environ.get("GITHUB_TOKEN"), os.environ.get("GITHUB_REPOSITORY"), os.environ.get("PR_NUMBER")
    if not (token and repo and pr):
        return
    req = urllib.request.Request(f"https://api.github.com/repos/{repo}/issues/{pr}/comments", method="POST",
                                 data=json.dumps({"body": body}).encode(),
                                 headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json"})
    try:
        urllib.request.urlopen(req, timeout=15).read()
    except Exception as exc:  # never fail the job because of a comment
        print(f"could not comment: {exc}")


def main(argv: list[str]) -> int:
    report = json.load(open(argv[1]))
    if not report["findings"]:
        return 0
    task = build_task(report, dict(os.environ))
    res = send_to_devin(task, title=f"Night Watch: blocked PR #{os.environ.get('PR_NUMBER', '?')}")
    if res["status"] == "sent":
        msg = f"Night Watch handed this PR to Devin for review and hardening: {res.get('session')}"
    elif res["status"] == "dry_run":
        msg = "Night Watch would hand this PR to Devin, but no DEVIN_API_KEY secret is set on this repository."
    else:
        msg = f"Night Watch could not reach Devin: {res.get('error')}"
    print(msg)
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a") as fh:
            fh.write(f"\n\n{msg}\n\n<details><summary>Task sent to Devin</summary>\n\n```\n{task}\n```\n</details>\n")
    comment("**Night Watch** :shield: " + msg + "\n\n---\n_Generated by Night Watch_")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
